#!/usr/bin/env python3
"""Converts a pixel-art SVG made of one-pixel-high `<rect>` runs into `crates/vantage-gui/src/pixel_art.rs`.

Usage: gen_pixel_art.py <svg> <output .rs> <CONST_NAME>
"""
import re
import sys


def main():
    svg, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    text = open(svg, encoding="utf-8").read()
    size = int(float(re.search(r'viewBox="0 0 (\d+(?:\.\d+)?) ', text).group(1)))
    runs = [(int(x), int(y), int(w)) for x, y, w, h in re.findall(r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"', text) if h == "1"]
    rows = ", ".join(f"[{x}, {y}, {w}]" for x, y, w in runs)
    body = (
        "//! Pixel-art icons: each is a square grid and the one-pixel-high runs that are lit. Generated by\n"
        "//! `tools/vantage-brand/gen_pixel_art.py` from supplied artwork; do not edit by hand.\n\n"
        "/// A pixel-art icon.\n#[derive(Debug, PartialEq, Eq)]\npub struct PixelArt {\n"
        "    /// The side of the square grid, in pixels.\n    pub size: u8,\n"
        "    /// The lit runs as `[x, y, width]`, each one pixel high.\n    pub runs: &'static [[u8; 3]],\n}\n\n"
        f"/// The honeycomb mark.\n#[rustfmt::skip]\npub static {name}: PixelArt = PixelArt {{ size: {size}, runs: &[{rows}] }};\n"
    )
    open(out, "w", newline="\n").write(body)
    print(size, len(runs))


if __name__ == "__main__":
    main()
