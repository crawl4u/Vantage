"""Generates crates/vantage-ui/src/brand.rs from the wordmark SVG: the logo as flattened filled and stroked
polygons, so the menu can draw it with the host's vector path renderer. Run from the repository root:

    python tools/vantage-brand/gen_brand.py
"""
import math
import re

SVG = "crates/vantage-ui/assets/vantage-wordmark.svg"
OUT = "crates/vantage-ui/src/brand.rs"
CURVE_STEPS = 10


def parse(d):
    tokens = re.findall(r"[MHVLCQZ]|-?\d*\.?\d+(?:e-?\d+)?", d)
    i = 0
    contours, cur, pos, start = [], [], (0.0, 0.0), (0.0, 0.0)
    cmd = None

    def num():
        nonlocal i
        v = float(tokens[i])
        i += 1
        return v

    while i < len(tokens):
        if re.fullmatch(r"[MHVLCQZ]", tokens[i]):
            cmd = tokens[i]
            i += 1
        if cmd == "M":
            if cur:
                contours.append(cur)
            pos = (num(), num())
            start = pos
            cur = [pos]
            cmd = "L"
        elif cmd == "L":
            pos = (num(), num())
            cur.append(pos)
        elif cmd == "H":
            pos = (num(), pos[1])
            cur.append(pos)
        elif cmd == "V":
            pos = (pos[0], num())
            cur.append(pos)
        elif cmd == "C":
            p1, p2, p3 = (num(), num()), (num(), num()), (num(), num())
            for k in range(1, CURVE_STEPS + 1):
                t = k / CURVE_STEPS
                u = 1 - t
                cur.append(tuple(u**3 * pos[a] + 3 * u * u * t * p1[a] + 3 * u * t * t * p2[a] + t**3 * p3[a] for a in (0, 1)))
            pos = p3
        elif cmd == "Q":
            p1, p2 = (num(), num()), (num(), num())
            for k in range(1, CURVE_STEPS + 1):
                t = k / CURVE_STEPS
                u = 1 - t
                cur.append(tuple(u * u * pos[a] + 2 * u * t * p1[a] + t * t * p2[a] for a in (0, 1)))
            pos = p2
        elif cmd == "Z":
            if cur:
                contours.append(cur)
            cur = []
            pos = start
    if cur:
        contours.append(cur)
    return contours


def bounds(c):
    xs = [p[0] for p in c]
    ys = [p[1] for p in c]
    return min(xs), min(ys), max(xs), max(ys)


def mix(a, b, t):
    return tuple(round(a[k] + (b[k] - a[k]) * t) for k in range(3))


def hexrgb(h):
    return tuple(int(h[k:k + 2], 16) for k in (1, 3, 5))


svg = open(SVG, encoding="utf-8").read()
paths = re.findall(r'<path[^>]* d="([^"]+)"', svg)
mark_d, word_d = paths[0], paths[2]

# The mark: a left half, mirrored for the right; scaled and placed as the SVG's group transform does.
tx, ty, sc = 377.88325396825405, 159.59325396825395, 0.45203373015873016
half = parse(mark_d)[0]
left = [(tx + x * sc, ty + y * sc) for x, y in half]
right = [(tx + (400 - x) * sc, ty + y * sc) for x, y in half]
mark = [left, right]
cx, cy, r = tx + 200 * sc, ty + 122 * sc, 21 * math.sqrt(2) * sc
diamond = [[(cx, cy - r), (cx + r, cy), (cx, cy + r), (cx - r, cy)]]

# The wordmark's letters: contours grouped by horizontal overlap.
contours = parse(word_d)
groups = []
for c in sorted(contours, key=lambda c: bounds(c)[0]):
    b = bounds(c)
    for g in groups:
        if b[0] < g["right"] and b[2] > g["left"]:
            g["contours"].append(c)
            g["left"] = min(g["left"], b[0])
            g["right"] = max(g["right"], b[2])
            break
    else:
        groups.append({"contours": [c], "left": b[0], "right": b[2]})

allpoints = [p for c in mark + diamond + contours for p in c]
x0 = min(p[0] for p in allpoints) - 6
y0 = min(p[1] for p in allpoints) - 6
x1 = max(p[0] for p in allpoints) + 6
y1 = max(p[1] for p in allpoints) + 6
VB = (x0, y0, x1 - x0, y1 - y0)

start, end = hexrgb("#A5B4FC"), hexrgb("#7DD3FC")
span = (groups[0]["left"], groups[-1]["right"])


def poly(c):
    return "&[" + ",".join(f"[{p[0] - x0:.1f},{p[1] - y0:.1f}]" for p in c) + "]"


def layer(rgb, contours_, stroke=None):
    return f"    Layer {{ rgb: 0x{rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X}, stroke: {stroke if stroke else 'None'}, contours: &[{','.join(poly(c) for c in contours_)}] }},\n"


out = []
out.append("//! The Vantage wordmark, as flattened polygons for the host's vector path renderer.\n")
out.append("//!\n//! Generated by `tools/vantage-brand/gen_brand.py` from `assets/vantage-wordmark.svg`; do not edit.\n")
out.append("//! The SVG's gradients are drawn as flat colours, one per layer (the letters step through the gradient).\n\n")
out.append("/// One filled or stroked set of contours.\n#[derive(Clone, Copy, Debug)]\npub struct Layer {\n    /// The colour as `0xRRGGBB`.\n    pub rgb: u32,\n    /// The stroke width in logo units, or `None` for an even-odd fill.\n    pub stroke: Option<f32>,\n    pub contours: &'static [&'static [[f32; 2]]],\n}\n\n")
out.append(f"/// The logo's size in its own units: width and height of the box the layers are placed in.\npub const SIZE: [f32; 2] = [{VB[2]:.1f}, {VB[3]:.1f}];\n\n")
out.append("/// The layers, back to front.\npub const LAYERS: &[Layer] = &[\n")
out.append(layer((0x45, 0x34, 0xBC), mark))
out.append(layer((0x7B, 0x9B, 0xF7), mark, stroke=f"Some({10 * sc:.2f})"))
out.append(layer((0xF7, 0xB5, 0x10), diamond))
out.append(layer((0xFF, 0xDC, 0x76), diamond, stroke=f"Some({8 * sc:.2f})"))
for g in groups:
    t = ((g["left"] + g["right"]) / 2 - span[0]) / (span[1] - span[0])
    out.append(layer(mix(start, end, t), g["contours"]))
out.append("];\n")
open(OUT, "w", encoding="utf-8", newline="\n").write("".join(out))
print("letters", len(groups), "points", sum(len(c) for c in allpoints), "size", VB[2:])
